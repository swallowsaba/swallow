/**
 * Cookie の模型（docs/lessons/web.md の web.b.06）。純粋な関数。curl の Cookie の働き（-b・-c）と同じ決まりで動く。
 *
 * - Set-Cookie を読んで札にする。Path が無ければ、頼んだ道のディレクトリ（RFC 6265 5.1.4）
 * - 頼む時は、名前（ホスト）・道（Path）・暗号化（Secure）が合う札だけを Cookie の見出しにする。長い Path の札を先に並べる
 * - 札の入れ物（クッキージャー）は、curl と同じ Netscape の形の文書で読み書きする。HttpOnly の札は行頭に #HttpOnly_ を付ける
 * - Secure の札は、暗号化していない頼み（http）からは受け取らない（手元を指す名前は除く。curl と同じ）
 */

export interface Cookie {
  /** 札を返すホスト（Domain を書かない札は、受け取ったホストだけ） */
  domain: string;
  path: string;
  secure: boolean;
  httpOnly: boolean;
  name: string;
  value: string;
}

export type CookieJar = readonly Cookie[];

/** 頼んだ道の既定の Path（最後の / の前まで。/ しか無ければ /） */
export function defaultPath(requestPath: string): string {
  const p = requestPath.split('?')[0] ?? '/';
  if (!p.startsWith('/')) return '/';
  const last = p.lastIndexOf('/');
  return last <= 0 ? '/' : p.slice(0, last);
}

/** 道が札の Path に合うか（RFC 6265 5.1.4 の path-match） */
export function pathMatches(requestPath: string, cookiePath: string): boolean {
  const p = (requestPath.split('?')[0] ?? '/') || '/';
  if (p === cookiePath) return true;
  if (!p.startsWith(cookiePath)) return false;
  return cookiePath.endsWith('/') || p[cookiePath.length] === '/';
}

/** Set-Cookie の値を読む。名前の無い物は null */
export function parseSetCookie(header: string, host: string, requestPath: string): Cookie | null {
  const [pair = '', ...attrs] = header.split(';').map((s) => s.trim());
  const eq = pair.indexOf('=');
  if (eq <= 0) return null;
  const cookie: Cookie = { domain: host.toLowerCase(), path: defaultPath(requestPath), secure: false, httpOnly: false, name: pair.slice(0, eq).trim(), value: pair.slice(eq + 1).trim() };
  for (const a of attrs) {
    const [k = '', ...v] = a.split('=');
    const key = k.trim().toLowerCase();
    const val = v.join('=').trim();
    if (key === 'path' && val.startsWith('/')) cookie.path = val;
    else if (key === 'secure') cookie.secure = true;
    else if (key === 'httponly') cookie.httpOnly = true;
  }
  return cookie;
}

/** 札を入れ物に足す（名前・ホスト・Path が同じ札は置き換える） */
export function addCookie(jar: CookieJar, c: Cookie): Cookie[] {
  return [...jar.filter((o) => !(o.name === c.name && o.domain === c.domain && o.path === c.path)), c];
}

/** 頼みに付ける札（Cookie の見出しの値）。合う札が無ければ空 */
export function cookieHeader(jar: CookieJar, scheme: 'http' | 'https', host: string, path: string): string {
  const h = host.toLowerCase();
  return jar
    .filter((c) => c.domain === h && pathMatches(path, c.path) && (!c.secure || scheme === 'https'))
    .sort((a, b) => b.path.length - a.path.length)
    .map((c) => `${c.name}=${c.value}`)
    .join('; ');
}

const JAR_HEAD = ['# Netscape HTTP Cookie File', '# https://curl.se/docs/http-cookies.html', '# This file was generated by libcurl! Edit at your own risk.', ''];

/** 入れ物の文書（curl -c が書く形） */
export function jarText(jar: CookieJar): string {
  const rows = jar.map((c) => [`${c.httpOnly ? '#HttpOnly_' : ''}${c.domain}`, 'FALSE', c.path, c.secure ? 'TRUE' : 'FALSE', '0', c.name, c.value].join('\t'));
  return `${[...JAR_HEAD, ...rows].join('\n')}\n`;
}

/** 入れ物の文書を読む（curl -b ファイル）。読めない行は飛ばす */
export function parseJar(text: string): Cookie[] {
  return text.split('\n').flatMap((raw) => {
    const httpOnly = raw.startsWith('#HttpOnly_');
    const line = httpOnly ? raw.slice('#HttpOnly_'.length) : raw;
    if (line.startsWith('#') || line.trim() === '') return [];
    const f = line.split('\t');
    if (f.length < 7) return [];
    const [domain = '', , path = '/', secure = 'FALSE', , name = '', value = ''] = f;
    return [{ domain: domain.replace(/^\./, '').toLowerCase(), path, secure: secure === 'TRUE', httpOnly, name, value }];
  });
}
